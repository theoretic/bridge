<?php namespace ProcessWire;

// the interface without depending on the theme: its file when the theme is there, else the same
// one-method interface declared here (docs/extensions.md 2)
if(!interface_exists("ProcessWire\\BridgeExtension", false)) {
	$bridgeExtensionFile = dirname(__DIR__) . '/AdminThemeBridge/BridgeExtension.php';
	if(is_file($bridgeExtensionFile)) {
		require_once($bridgeExtensionFile);
	} else {
		interface BridgeExtension { public function getBridgeExtension(); }
	}
	unset($bridgeExtensionFile);
}

/**
 * BridgeSample
 *
 * A Bridge extension (extension contract 0.2, docs/extensions.md): a module that fills the admin
 * shell's slots through its manifest and uses only the theme's published surface.
 *
 * Generated by: php tools/scaffold-extension.php BridgeSample --slots=masthead-right,user-nav,content-head-buttons,footer,drawer,body --module --styles
 *
 * MIT.
 */
class BridgeSample extends WireData implements Module, ConfigurableModule, BridgeExtension {

	public static function getModuleInfo() {
		return array(
			'title' => 'BridgeSample',
			'version' => '0.1.0',
			'summary' => 'A Bridge extension.',
			'requires' => 'AdminThemeBridge',
		);
	}

	/**
	 * The manifest (docs/extensions.md 2): a fixed array; asked before init(), reads no config
	 *
	 * @return array
	 *
	 */
	public function getBridgeExtension() {
		return array(
			'contract' => '^0.2',
			'module' => 'BridgeSample.mjs',
			'styles' => array('BridgeSample.css'),
			'tokens' => array('--muted-foreground'),
			'slots' => array(
				'masthead-right' => 'slotMastheadRight',
				'user-nav' => 'slotUserNav',
				'content-head-buttons' => 'slotContentHeadButtons',
				'footer' => 'slotFooter',
				'drawer' => 'slotDrawer',
				'body' => 'slotBody',
			),
		);
	}

	/**
	 * The `masthead-right` slot (docs/extensions.md 4); the theme wraps it in an element of its own
	 *
	 * @param string $slot The slot's name
	 * @return string
	 *
	 */
	public function slotMastheadRight($slot) {
		return "<pw-bridgesample data-slot='" . $this->wire()->sanitizer->entities($slot) . "'>" . $this->wire()->sanitizer->entities($this->_('BridgeSample')) . "</pw-bridgesample>";
	}

	/**
	 * The `user-nav` slot (docs/extensions.md 4); the theme wraps it in an element of its own

	}

	/**
	 * The `content-head-buttons` slot (docs/extensions.md 4); the theme wraps it in an element of its own
	 *
	 * @param string $slot The slot's name
	 * @return string
	 *
	 */
	public function slotContentHeadButtons($slot) {
		return "<pw-bridgesample data-slot='" . $this->wire()->sanitizer->entities($slot) . "'>" . $this->wire()->sanitizer->entities($this->_('BridgeSample')) . "</pw-bridgesample>";

	/**
	 * The `drawer` slot: the drawer's body, its label and icon (a button beside the logo opens it)
	 *
	 * @param string $slot The slot's name
	 * @return array
	 *
	 */
	public function slotDrawer($slot) {
		$sanitizer = $this->wire()->sanitizer;
		return array(
			'content' => "<pw-bridgesample data-slot='drawer'><p>" . $sanitizer->entities($this->_('Drawer of the extension.')) . "</p></pw-bridgesample>",
			'label' => $this->_('BridgeSample'),
			'icon' => 'puzzle-piece',
		);
	}


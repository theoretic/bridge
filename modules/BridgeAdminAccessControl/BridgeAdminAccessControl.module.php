<?php namespace ProcessWire;

require_once(__DIR__ . '/lib/AccessRules.php');

/**
 * BridgeAdminAccessControl
 *
 * A Bridge extension (written for extension contract ^0.1, docs/extensions.md): per-role access
 * control to the page tree, its subtrees and the four core top-level admin menus. Rules only ever
 * narrow what the core grants: docs/access-control.md.
 *
 * A rule is one role's, on one page, with or without its descendants. Per role the nearest rule
 * decides, no rule allows; across the user's roles any deny wins. The hooks only ever turn the
 * core's yes into a no, on the core's own seams, so they hold under any admin theme.
 *
 * Generated by tools/scaffold-extension.php, then shaped. Original work, MIT.
 */
class BridgeAdminAccessControl extends WireData implements Module, ConfigurableModule {

	public static function getModuleInfo() {
		return array(
			'title' => 'Bridge admin access control',
			'version' => '0.1.1',
			'summary' => 'Per-role access control to the page tree, its subtrees and the top-level admin menus.',
			'author' => 'Alexei Tarasov',
			'autoload' => 'template=admin',
			'singular' => true,
			'requires' => 'ProcessWire>=3.0.227, PHP>=8.1',
			'icon' => 'lock',
			'href' => 'https://github.com/theoretic/bridge',
			// Bridge extension manifest (docs/extensions.md 2), declarative: no dependency on the theme
			'bridge' => array(
				'contract' => '^0.1',
				'hooks' => array('navCacheKey', 'drawerNames'),
			),
		);
	}

	/** The user may have the page */
	const ALLOW = 'allow';

	/** The user may not have the page */
	const DENY = 'deny';

	/** Denied, but an allowed page lies below it: stays in the tree as the way there */
	const DENY_PASS = 'deny-pass';

	/** The core's Pages menu, where the admin home sends everyone */
	const pagesMenuId = 3;

	/** The core's Modules menu, the way to the editor of the rules */
	const modulesMenuId = 21;

	/**
	 * @var BridgeAccessRules|null The saved rules, loaded once (engine())
	 */
	protected $engine = null;

	/**
	 * @var array Role id => page id => rule
	 */
	protected $roleIndex = null;

	/**
	 * @var array User id => rules of their roles
	 */
	protected $userRules = array();

	/**
	 * @var array User id => page id => verdict
	 */
	protected $verdicts = array();

	/**
	 * @var array User id => ids of the pages with an allowed page below them
	 */
	protected $passThrough = array();

	/**
	 * @var array Role id => page id => does a child of that page inherit a deny
	 */
	protected $inherited = array();

	/**
	 * @var array Page id => parent id
	 */
	protected $parentIds = array();

	/**
	 * @var bool Are the enforcement hooks in place?
	 */
	protected $enforcing = false;

	/**
	 * @var string This request's suffix for the selector group names (requestClause())
	 */
	protected $groupSuffix = '';

	public function __construct() {
		parent::__construct();
		$this->set('rules', array());
		$this->set('rulesVersion', 0);
		$this->set('apiGuard', 1);
	}

	public function init() {
		$this->addHookAfter('Pages::deleted', $this, 'hookPageDeleted');
		$this->addHookBefore('Modules::saveConfig', $this, 'hookSaveConfig');
		if(count($this->rulesFor($this->wire()->user))) $this->addEnforcementHooks();
	}

	/**
	 * Add the hooks that enforce the rules. A user without rules never gets here (init()); each
	 * handler still asks about the current user, which a hook or a test may have changed since.
	 *
	 * The `Page::` hooks run after PagePermissions (priority 200), which sets the return value
	 * unconditionally. None of them answers for an admin page: a non-viewable admin page renders
	 * the login page (PagesRequest::checkAccess()), so menus are filtered in the nav array and
	 * requests refused in ProcessController::execute.
	 *
	 */
	public function addEnforcementHooks() {
		if($this->enforcing) return;
		$this->enforcing = true;
		$handlers = array(
			'listable' => 'hookPageSeen',
			'viewable' => 'hookPageSeen',
			'editable' => 'hookPageChanged',
			'publishable' => 'hookPageChanged',
			'addable' => 'hookPageChanged',
			'moveable' => 'hookPageChanged',
			'deleteable' => 'hookPageChanged',
			'deletable' => 'hookPageChanged',
			'trashable' => 'hookPageChanged',
			'restorable' => 'hookPageChanged',
			'sortable' => 'hookPageChanged',
			'cloneable' => 'hookPageChanged',
		);
		foreach($handlers as $method => $handler) {
			$this->addHookAfter("Page::$method", $this, $handler, array('priority' => 200));
		}
		$this->addHookBefore('ProcessController::execute', $this, 'hookControllerExecute');
		$this->addHookAfter('AdminThemeFramework::getPrimaryNavArray', $this, 'hookPrimaryNav');
		$this->addHookBefore('ProcessHome::execute', $this, 'hookHomeExecute');
		$this->addHookAfter('ProcessPageSearch::findReady', $this, 'hookFindSelector');
		$this->addHookAfter('ProcessPageLister::getSelector', $this, 'hookFindSelector');
		foreach(array('saveReady', 'saveFieldReady', 'trashReady', 'restoreReady', 'deleteReady') as $method) {
			$this->addHookBefore("Pages::$method", $this, 'hookPageGuard');
		}
		if($this->bridgeThemePresent()) {
			$this->addHookAfter('AdminThemeBridge::navCacheKey', $this, 'hookNavCacheKey');
			$this->addHookAfter('AdminThemeBridge::drawerNames', $this, 'hookDrawerNames');
		}
	}

	/**
	 * Hook after Page::listable and Page::viewable: only a plain deny hides a page, a pass-through
	 * stays as the way to what is allowed below it
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookPageSeen(HookEvent $event) {
		if($event->return === false) return;
		if($this->contentVerdict($event->object) === self::DENY) $event->return = false;
	}

	/**
	 * Hook after the Page predicates that change a page (edit, publish, add, move, sort, clone,
	 * trash, restore, delete): denied, pass-through included
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookPageChanged(HookEvent $event) {
		if($event->return === false) return;
		if($this->contentVerdict($event->object) !== self::ALLOW) $event->return = false;
	}

	/**
	 * Hook before ProcessController::execute: refuse a request under a denied core menu
	 *
	 * @param HookEvent $event
	 * @throws WirePermissionException
	 *
	 */
	public function hookControllerExecute(HookEvent $event) {
		$page = $this->wire()->page;
		if(!$page || !$page->id || !$this->menuGateDenies($page, $this->wire()->user)) return;
		throw new WirePermissionException($this->_('You do not have access to this section.'));
	}

	/**
	 * Hook after AdminThemeFramework::getPrimaryNavArray: drop the denied core menus, every other
	 * item stays as the core built it
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookPrimaryNav(HookEvent $event) {
		$user = $this->wire()->user;
		if(!count($this->rulesFor($user)) || !is_array($event->return)) return;
		$menus = $this->coreMenus();
		$items = array();
		foreach($event->return as $item) {
			$id = isset($item['id']) ? (int) $item['id'] : 0;
			if(!isset($menus[$id]) || !$this->menuDenied($menus[$id], $user)) $items[] = $item;
		}
		$event->return = $items;
	}

	/**
	 * Hook before ProcessHome::execute, which sends everyone to the page tree: with Pages denied,
	 * go to the first menu that is left, or the user's profile
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookHomeExecute(HookEvent $event) {
		if($this->pagesMenuDenied()) $this->wire()->session->location($this->landingUrl());
	}

	/**
	 * Hook after AdminThemeBridge::navCacheKey: a user with rules gets a key of their own, so a
	 * changed rule set is a miss on that user's next request
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookNavCacheKey(HookEvent $event) {
		$user = $this->wire()->user;
		if(!count($this->rulesFor($user))) return;
		$event->return .= '-acl' . (int) $this->get('rulesVersion') . '-' . (int) $user->id;
	}

	/**
	 * Hook after AdminThemeBridge::drawerNames: with Pages denied the page tree drawer would open
	 * empty (its request is refused), so it goes; the other drawers stay
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookDrawerNames(HookEvent $event) {
		if(!is_array($event->return) || !$this->pagesMenuDenied()) return;
		$event->return = array_values(array_diff($event->return, array('tree')));
	}

	/**
	 * Hook after ProcessPageSearch::findReady (search, autocomplete, live search) and
	 * ProcessPageLister::getSelector: these screens find pages and ask no page about access, so the
	 * rules go into the selector
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookFindSelector(HookEvent $event) {
		$clause = $this->requestClause($this->wire()->user);
		if($clause !== '') $event->return = ltrim($event->return . $clause, ', ');
	}

	/**
	 * The clause as the hook appends it: selectorClause() with this request's suffix on the group
	 * names. Members of one group name are alternatives, so a filter a user posts (or a bookmark
	 * saved earlier) that used the module's name would open what the group closes; a name that
	 * cannot be known beforehand keeps such a group apart.
	 *
	 * @param User $user
	 * @return string
	 *
	 */
	public function requestClause(User $user) {
		if($this->groupSuffix === '') $this->groupSuffix = '_' . bin2hex(random_bytes(8));
		return $this->selectorClause($user, $this->groupSuffix);
	}

	/**
	 * Hook before Pages::saveReady, saveFieldReady, trashReady, restoreReady and deleteReady: in an
	 * admin request, whatever code asks for it, a denied page is not changed. For a page being added,
	 * the rules' verdict on its parent decides; a page being moved counts as added under its new
	 * parent. restoreReady is needed beside saveReady: a restore, also the one inside a save, clears
	 * the trash status in the database before saveReady is reached. saveFieldReady is needed beside
	 * saveReady: Pages::saveField() (and saveFields(), which calls it per field) fires only that one;
	 * argument 0 is the page there too. A page whose parent was changed in memory and whose field is
	 * then saved with saveField() is judged as a move (old and new place both allowed): stricter than
	 * a field save needs, never looser. savePageOrFieldReady is not hooked (it would run the guard
	 * twice per save). A save made with the core's noHooks option passes no hook at all.
	 *
	 * @param HookEvent $event
	 * @throws WirePermissionException
	 *
	 */
	public function hookPageGuard(HookEvent $event) {
		if(!$this->wire()->config->admin || !$this->get('apiGuard')) return;
		$page = $event->arguments(0);
		$from = $page->isNew() ? null : $page->parentPrevious;
		if($from && (int) $from->id !== (int) $page->parent_id) {
			$allowed = $this->moveAllowed($page, $from);
		} else {
			$allowed = $this->contentVerdict($page->isNew() ? $page->parent() : $page) === self::ALLOW;
		}
		if(!$allowed) throw new WirePermissionException($this->_('You do not have access to this page.'));
	}

	/**
	 * May the current user's rules let this page leave one parent for another? It must be allowed
	 * where it was, and its new parent and the page in its new place must be allowed. The trash is
	 * no place the rules speak of (a deny on the home page reaches it): going there is judged by
	 * the old place only, coming back by the new one.
	 *
	 * What was worked out before the move no longer holds (ProcessPageEdit asks editable() first
	 * and sets a posted parent afterwards), so it is dropped.
	 *
	 * @param Page $page
	 * @param Page $from The previous parent
	 * @return bool
	 *
	 */
	protected function moveAllowed(Page $page, Page $from) {
		if(!$from->isTrash() && !$this->isAdminPage($from) && $this->userDenied($page, $this->wire()->user, $from)) return false;
		$this->forget();
		$to = $page->parent();
		if($to->isTrash()) return true;
		return $this->contentVerdict($to) === self::ALLOW && $this->contentVerdict($page) === self::ALLOW;
	}

	/**
	 * Does the gate refuse this admin page? It does when the page is one of the four core menus or
	 * lies under one, and that menu is denied to the user. Any other admin page is never refused.
	 *
	 * @param Page $requested
	 * @param User $user
	 * @return bool
	 *
	 */
	public function menuGateDenies(Page $requested, User $user) {
		if(!count($this->rulesFor($user))) return false;
		$menus = $this->coreMenus();
		$adminRoot = (int) $this->wire()->config->adminRootPageID;
		$id = (int) $requested->id;
		while($id > 0 && $id !== $adminRoot) {
			if(isset($menus[$id])) return $this->menuDenied($menus[$id], $user);
			$id = $this->parentId($id);
		}
		return false;
	}

	/**
	 * Set a property: new rules drop what was worked out from the old ones
	 *
	 * @param string $key
	 * @param mixed $value
	 * @return $this
	 *
	 */
	public function set($key, $value) {
		if($key === 'rules') $this->forget();
		return parent::set($key, $value);
	}

	/**
	 * Hook after Pages::deleted: a deleted page's rules go with it
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookPageDeleted(HookEvent $event) {
		$rules = $this->accessRules();
		if($rules->removePage((int) $event->arguments(0)->id)) $this->saveRules($rules);
	}

	/**
	 * Hook before Modules::saveConfig: the rule editor's inputs are transient (their names start
	 * with `_`, the core stores none of them), so a save of the config screen turns them into the
	 * `rules` list here. Any other save of the config passes untouched.
	 *
	 * @param HookEvent $event
	 *
	 */
	public function hookSaveConfig(HookEvent $event) {
		$data = $event->arguments(1);
		if(!is_array($data) || wireClassName($event->arguments(0), false) !== $this->className()) return;
		if(!$this->wire()->input->post('submit_save_module')) return;
		$rules = $this->postedRules($data)->toConfig()['rules'];
		$before = isset($data['rules']) && is_array($data['rules']) ? $data['rules'] : array();
		$version = isset($data['rulesVersion']) ? (int) $data['rulesVersion'] : 0;
		if($rules !== $before) $version++;
		$data['rules'] = $rules;
		$data['rulesVersion'] = $version;
		$event->arguments(1, $data);
		$this->set('rules', $rules);
		$this->set('rulesVersion', $version);
	}

	/**
	 * The rules as the posted form leaves them. A role goes all or nothing: what is refused for it
	 * is reported and leaves that role's rules as they were.
	 *
	 * @param array $data The module's config
	 * @return BridgeAccessRules
	 *
	 */
	protected function postedRules(array $data) {
		$input = $this->wire()->input;
		$rules = $this->wire(new BridgeAccessRules())->fromConfig($data);
		$saved = $rules->rules(); // the Remove boxes hold indexes into this list
		foreach($this->editableRoles() as $role) {
			$roleId = (int) $role->id;
			if(!$input->post->int("_acl_role_$roleId")) continue; // not on the form that was posted
			$edited = clone $rules;
			try {
				$this->applyRoleInputs($edited, $roleId, $saved);
			} catch(WireException $e) {
				$this->error($role->name . ': ' . $e->getMessage());
				continue;
			}
			if($this->locksOutEditor($edited, $role)) {
				$this->error(sprintf(
					$this->_('The rules of role %s were not changed: denying Modules would lock you out of this screen.'),
					$role->name
				));
				continue;
			}
			$rules = $edited;
		}
		return $rules;
	}

	/**
	 * Apply one role's inputs: Remove first (the indexes are the saved list's), then the menus, then
	 * the new rule, so a rule added on a menu page is not undone by that menu's box
	 *
	 * @param BridgeAccessRules $rules
	 * @param int $roleId
	 * @param array $saved The rules as saved, by index
	 * @throws WireException When a rule is refused
	 *
	 */
	protected function applyRoleInputs(BridgeAccessRules $rules, int $roleId, array $saved) {
		$post = $this->wire()->input->post;
		foreach($post->intArray("_acl_remove_$roleId") as $index) {
			if(isset($saved[$index]) && $saved[$index]['role'] === $roleId) $rules->removeRule($roleId, $saved[$index]['page']);
		}
		$allowed = array_flip($post->intArray("_acl_menus_$roleId"));
		foreach(array_keys($this->coreMenus()) as $menuId) {
			if(isset($allowed[$menuId])) {
				$rules->removeRule($roleId, $menuId);
			} else {
				$rules->add(array('role' => $roleId, 'page' => $menuId, 'mode' => BridgeAccessRules::modeDeny, 'inherit' => true));
			}
		}
		$pageId = (int) $post->int("_acl_page_$roleId");
		if($pageId < 1) return;
		$rules->add(array(
			'role' => $roleId,
			'page' => $pageId,
			'mode' => (string) $post->name("_acl_mode_$roleId"),
			'inherit' => (bool) $post->int("_acl_inherit_$roleId"),
		));
	}

	/**
	 * Would these rules take Modules away from the user saving them? The screen is open to anyone
	 * with `module-admin`, who must not be able to lock themselves out of it. A superuser has no
	 * rules, so it never applies to one.
	 *
	 * @param BridgeAccessRules $rules
	 * @param Role $role The role being changed
	 * @return bool
	 *
	 */
	protected function locksOutEditor(BridgeAccessRules $rules, Role $role) {
		$user = $this->wire()->user;
		if($user->isSuperuser() || !$user->hasRole($role)) return false;
		foreach($rules->rules() as $rule) {
			if($rule['role'] === (int) $role->id && $rule['page'] === self::modulesMenuId && $rule['mode'] === BridgeAccessRules::modeDeny) return true;
		}
		return false;
	}

	/**
	 * A copy of the saved rules, to change and give to saveRules()
	 *
	 * @return BridgeAccessRules
	 *
	 */
	public function accessRules() {
		return clone $this->engine();
	}

	/**
	 * Save a changed rule set: writes the module's config and bumps the stamp `rulesVersion`
	 *
	 * @param BridgeAccessRules $rules
	 *
	 */
	public function saveRules(BridgeAccessRules $rules) {
		$modules = $this->wire()->modules;
		$data = array_merge($modules->getConfig($this->className()), $rules->toConfig());
		$data['rulesVersion'] = (int) $this->get('rulesVersion') + 1;
		$modules->saveConfig($this->className(), $data);
		$this->set('rules', $data['rules']);
		$this->set('rulesVersion', $data['rulesVersion']);
	}

	/**
	 * The four core top-level admin items
	 *
	 * @return array id => Page
	 *
	 */
	public function coreMenus() {
		return $this->engine()->coreMenus();
	}

	/**
	 * Is AdminThemeBridge there, in a version that has the hookable navCacheKey()? From the module
	 * info cache, without loading the theme's class.
	 *
	 * @return bool
	 *
	 */
	public function bridgeThemePresent() {
		$modules = $this->wire()->modules;
		if(!$modules->isInstalled('AdminThemeBridge')) return false;
		$info = $modules->getModuleInfo('AdminThemeBridge');
		return version_compare((string) $info['version'], '0.28.0', '>=');
	}

	/**
	 * The rules that apply to a user; none for a superuser or the guest user
	 *
	 * @param User $user
	 * @return array
	 *
	 */
	public function rulesFor(User $user) {
		$id = (int) $user->id;
		if(!isset($this->userRules[$id])) {
			$exempt = $user->isSuperuser() || $user->isGuest();
			$this->userRules[$id] = $exempt ? array() : $this->engine()->forRoles($user->roles->explode('id'));
		}
		return $this->userRules[$id];
	}

	/**
	 * One role's verdict on a page: the nearest rule on the page or, with inherit, on an ancestor
	 *
	 * @param Page $page
	 * @param Role $role
	 * @return string self::ALLOW or self::DENY
	 *
	 */
	public function roleVerdict(Page $page, Role $role) {
		return $page->id && $this->roleDenies((int) $role->id, $page) ? self::DENY : self::ALLOW;
	}

	/**
	 * A user's verdict on a page. Any role's deny wins; a denied page with an allowed page below it
	 * (a page no role of the user denies, named by an allow rule) is DENY_PASS.
	 *
	 * @param Page $page
	 * @param User|null $user Default: the current user
	 * @return string self::ALLOW, self::DENY or self::DENY_PASS
	 *
	 */
	public function verdict(Page $page, ?User $user = null) {
		if(!$user) $user = $this->wire()->user;
		$userId = (int) $user->id;
		$pageId = (int) $page->id;
		if(isset($this->verdicts[$userId][$pageId])) return $this->verdicts[$userId][$pageId];
		$verdict = self::ALLOW;
		if($pageId && $this->userDenied($page, $user)) {
			$verdict = isset($this->passThroughIds($user)[$pageId]) ? self::DENY_PASS : self::DENY;
		}
		return $this->verdicts[$userId][$pageId] = $verdict;
	}

	/**
	 * The content pages the user's roles deny by a rule of their own
	 *
	 * @param User $user
	 * @return array Page id => does the deny cover the descendants (any role's inherit counts)
	 *
	 */
	public function deniedRoots(User $user) {
		$menus = $this->coreMenus();
		$roots = array();
		foreach($this->rulesFor($user) as $rule) {
			if($rule['mode'] !== BridgeAccessRules::modeDeny || isset($menus[$rule['page']])) continue;
			$roots[$rule['page']] = !empty($roots[$rule['page']]) || $rule['inherit'];
		}
		return $roots;
	}

	/**
	 * What the user's denies add to a selector, for the screens that find pages:
	 *
	 * - a deny with inherit: `, id!=R, has_parent!=R`
	 * - a deny without inherit: `, id!=R`
	 * - a deny with inherit and allowed pages below it, one named group per denied page (names AND,
	 *   the members of one name OR): `, rR=(id!=R, has_parent!=R), rR=(id=E), rR=(has_parent=E)`;
	 *   `has_parent=E` only when the allow covers what is below E
	 *
	 * A deny on the home page has the admin root as an exception, since it says nothing about
	 * admin pages: `, r1=(id!=1, has_parent!=1), r1=(id=2), r1=(has_parent=2)`.
	 *
	 * The hooks use requestClause(), which adds a per-request suffix to `rR`.
	 *
	 * @param User $user
	 * @param string $groupSuffix Appended to each group name
	 * @return string Empty when the user has no denied page; else it starts with a comma
	 *
	 */
	public function selectorClause(User $user, $groupSuffix = '') {
		$clause = '';
		foreach($this->deniedRoots($user) as $root => $inherit) {
			if(!$inherit) {
				$clause .= ", id!=$root";
				continue;
			}
			$exceptions = $this->exceptionsBelow($root, $user);
			if(!count($exceptions)) {
				$clause .= ", id!=$root, has_parent!=$root";
				continue;
			}
			$group = "r$root$groupSuffix";
			$clause .= ", $group=(id!=$root, has_parent!=$root)";
			foreach($exceptions as $id => $withChildren) {
				$clause .= ", $group=(id=$id)";
				if($withChildren) $clause .= ", $group=(has_parent=$id)";
			}
		}
		return $clause;
	}

	/**
	 * Is this core top-level admin item denied to the user? Only a rule on the item itself counts:
	 * a deny on the home page is about content, though the admin root lies under home.
	 *
	 * @param Page $topLevel
	 * @param User $user
	 * @return bool
	 *
	 */
	public function menuDenied(Page $topLevel, User $user) {
		if(!isset($this->coreMenus()[$topLevel->id])) return false;
		foreach($this->rulesFor($user) as $rule) {
			if($rule['page'] === (int) $topLevel->id && $rule['mode'] === BridgeAccessRules::modeDeny) return true;
		}
		return false;
	}

	/**
	 * The config screen: the one stored setting, the rule editor per role and a note on the model.
	 * Every input of the editor has a name starting with `_`, so the core stores none of them:
	 * hookSaveConfig() reads them.
	 *
	 * @param InputfieldWrapper $inputfields
	 *
	 */
	public function getModuleConfigInputfields(InputfieldWrapper $inputfields) {
		$modules = $this->wire()->modules;
		/** @var InputfieldCheckbox $f */
		$f = $modules->get('InputfieldCheckbox');
		$f->attr('name', 'apiGuard');

	/**
	 * The roles that can carry rules
	 *
	 * @return Role[]
	 *
	 */
	protected function editableRoles() {
		$config = $this->wire()->config;
		$exempt = array((int) $config->superUserRolePageID, (int) $config->guestUserRolePageID);
		$out = array();
		foreach($this->wire()->roles->find('include=all, sort=name') as $role) {
			if(!in_array((int) $role->id, $exempt, true)) $out[] = $role;
		}
		return $out;
	}

	/**
	 * One role's part of the editor: its menus, its page rules and a new rule. Collapsed when the
	 * role has no rules.
	 *
	 * @param Role $role
	 * @return InputfieldFieldset
	 *
	 */
	protected function roleFieldset(Role $role) {
		$modules = $this->wire()->modules;
		$pages = $this->wire()->pages;
		$roleId = (int) $role->id;
		$menus = $this->coreMenus();
		$denied = array();
		$pageRules = array();
		foreach($this->engine()->rules() as $index => $rule) {
			if($rule['role'] !== $roleId) continue;
			if(isset($menus[$rule['page']])) {
				$denied[$rule['page']] = true;
			} else if($pages->get($rule['page'])->id) {
				$pageRules[$index] = $rule;
			}
		}

		/** @var InputfieldFieldset $set */
		$set = $modules->get('InputfieldFieldset');
		$set->attr('name', "_acl_set_$roleId");
		$set->label = sprintf($this->_('Role: %s'), $role->name);
		$set->collapsed = count($denied) || count($pageRules) ? Inputfield::collapsedNo : Inputfield::collapsedYes;

		/** @var InputfieldHidden $seen */
		$seen = $modules->get('InputfieldHidden');
		$seen->attr('name', "_acl_role_$roleId");
		$seen->attr('value', $roleId);
		$set->add($seen);

		/** @var InputfieldCheckboxes $f */
		$f = $modules->get('InputfieldCheckboxes');
		$f->attr('name', "_acl_menus_$roleId");
		$f->label = $this->_('Admin menus');
		$f->description = $this->_('A menu that is not ticked is denied to this role, with everything under it.');
		$value = array();
		foreach($menus as $id => $menu) {
			$f->addOption($id, (string) $menu->get('title|name'));
			if(!isset($denied[$id])) $value[] = $id;
		}
		$f->attr('value', $value);
		$set->add($f);

		$set->add($this->pageRulesTable($roleId, $pageRules));
		if(count($pageRules)) {
			$f = $modules->get('InputfieldCheckboxes');
			$f->attr('name', "_acl_remove_$roleId");
			$f->label = $this->_('Remove');
			foreach($pageRules as $index => $rule) {
				$f->addOption($index, $pages->get($rule['page'])->path . ' (' . $this->modeLabel($rule) . ')');
			}
			$set->add($f);
		}

		/** @var InputfieldFieldset $add */
		$add = $modules->get('InputfieldFieldset');
		$add->attr('name', "_acl_add_$roleId");
		$add->label = $this->_('Add rule');

		/** @var InputfieldPageListSelect $f */
		$f = $modules->get('InputfieldPageListSelect');
		$f->attr('name', "_acl_page_$roleId");
		$f->label = $this->_('Page');
		$f->set('parent_id', 0); // the tree starts at the home page, which can be picked
		$add->add($f);

		/** @var InputfieldRadios $f */
		$f = $modules->get('InputfieldRadios');
		$f->attr('name', "_acl_mode_$roleId");
		$f->label = $this->_('Access');
		$f->addOption(BridgeAccessRules::modeDeny, $this->_('Deny'));
		$f->addOption(BridgeAccessRules::modeAllow, $this->_('Allow'));
		$f->attr('value', BridgeAccessRules::modeDeny);
		$f->columnWidth = 50;
		$add->add($f);

		/** @var InputfieldCheckbox $f */
		$f = $modules->get('InputfieldCheckbox');
		$f->attr('name', "_acl_inherit_$roleId");
		$f->attr('value', 1);
		$f->label = $this->_('Below the page');
		$f->label2 = $this->_('Also applies to what is below the page');
		$f->checked(true);
		$f->columnWidth = 50;
		$add->add($f);

		$set->add($add);
		return $set;
	}

	/**
	 * The table of a role's page rules
	 *
	 * @param int $roleId
	 * @param array $pageRules
	 * @return InputfieldMarkup
	 *
	 */
	protected function pageRulesTable(int $roleId, array $pageRules) {
		$modules = $this->wire()->modules;
		/** @var InputfieldMarkup $f */
		$f = $modules->get('InputfieldMarkup');
		$f->attr('name', "_acl_rules_$roleId");
		$f->label = $this->_('Page rules');
		if(!count($pageRules)) {
			$f->value = '<p>' . $this->wire()->sanitizer->entities($this->_('No page rules yet.')) . '</p>';
			return $f;
		}
		$pages = $this->wire()->pages;
		/** @var MarkupAdminDataTable $table */
		$table = $modules->get('MarkupAdminDataTable');
		$table->setSortable(false);
		$table->headerRow(array($this->_('Page'), $this->_('Access'), $this->_('Applies to')));
		foreach($pageRules as $rule) {
			$table->row(array(
				$pages->get($rule['page'])->path,
				$this->modeLabel($rule),
				$rule['inherit'] ? $this->_('The page and what is below it') : $this->_('The page only'),
			));
		}
		$f->value = $table->render();
		return $f;
	}

	/**
	 * A rule's mode, for a person
	 *
	 * @param array $rule
	 * @return string
	 *
	 */
	protected function modeLabel(array $rule) {
		return $rule['mode'] === BridgeAccessRules::modeAllow ? $this->_('Allow') : $this->_('Deny');
	}

	/**
	 * Is the Pages menu denied to the current user?
	 *
	 * @return bool
	 *
	 */
	protected function pagesMenuDenied() {
		$menus = $this->coreMenus();
		return isset($menus[self::pagesMenuId]) && $this->menuDenied($menus[self::pagesMenuId], $this->wire()->user);
	}

	/**
	 * The current user's verdict on a page the rules can reach: an admin page, a page not saved yet
	 * and a user without rules are always allowed
	 *
	 * @param Page $page
	 * @return string self::ALLOW, self::DENY or self::DENY_PASS
	 *
	 */
	protected function contentVerdict(Page $page) {
		$user = $this->wire()->user;
		if(!$page->id || !count($this->rulesFor($user)) || $this->isAdminPage($page)) return self::ALLOW;
		return $this->verdict($page, $user);
	}

	/**
	 * Is this the admin root or a page under it?
	 *
	 * @param Page $page
	 * @return bool
	 *
	 */
	protected function isAdminPage(Page $page) {
		$adminRoot = (int) $this->wire()->config->adminRootPageID;
		$id = (int) $page->id;
		if($id === $adminRoot) return true;
		$this->parentIds[$id] = (int) $page->parent_id;
		while($id > 0 && $id !== $adminRoot) $id = $this->parentId($id);
		return $id === $adminRoot;
	}

	/**
	 * Where a user with no Pages menu starts: the first item of the menu, or the profile
	 *
	 * @return string URL
	 *
	 */
	protected function landingUrl() {
		$theme = $this->wire('adminTheme');
		if($theme instanceof AdminThemeFramework) {
			foreach($theme->getPrimaryNavArray() as $item) {
				if(!empty($item['url'])) return $item['url'];
			}
		}
		return $this->wire()->config->urls->admin . 'profile/';
	}

	/**
	 * The saved rules, loaded once
	 *
	 * @return BridgeAccessRules
	 *
	 */
	protected function engine() {
		if($this->engine === null) {
			$this->engine = $this->wire(new BridgeAccessRules())->fromConfig(array('rules' => $this->get('rules')));
		}
		return $this->engine;
	}

	/**
	 * Drop everything worked out from the rules
	 *
	 */
	protected function forget() {
		$this->engine = null;
		$this->roleIndex = null;
		$this->userRules = array();
		$this->verdicts = array();
		$this->passThrough = array();
		$this->inherited = array();
	}

	/**
	 * The usable rules by role and page
	 *
	 * @return array Role id => page id => rule
	 *
	 */
	protected function roleIndex() {
		if($this->roleIndex === null) {
			$this->roleIndex = array();
			$engine = $this->engine();
			foreach($engine->forRoles(array_column($engine->rules(), 'role')) as $rule) {
				$this->roleIndex[$rule['role']][$rule['page']] = $rule;
			}
		}
		return $this->roleIndex;
	}

	/**
	 * Does the nearest rule of this role on the page or above it deny?
	 *
	 * Rules above the admin root say nothing about admin pages: a deny on the home page with
	 * inherit denies the content, not the admin.
	 *
	 * @param int $roleId
	 * @param Page $page
	 * @param Page|null $parent Ask as if the page were under this parent (default: where it is)
	 * @return bool
	 *
	 */
	protected function roleDenies(int $roleId, Page $page, ?Page $parent = null) {
		$pageId = (int) $page->id;
		$rules = $this->roleIndex()[$roleId] ?? array();
		if(!count($rules)) return false;
		if(isset($rules[$pageId])) return $rules[$pageId]['mode'] === BridgeAccessRules::modeDeny;
		if($pageId === (int) $this->wire()->config->adminRootPageID) return false;
		if($parent) return $this->inheritedDeny($roleId, (int) $parent->id, $rules);
		$this->parentIds[$pageId] = (int) $page->parent_id;
		return $this->inheritedDeny($roleId, $this->parentIds[$pageId], $rules);
	}

	/**
	 * Walk up from a page: does the nearest rule with inherit deny? What the walk finds holds for
	 * every page on the way, so siblings share it.
	 *
	 * @param int $roleId
	 * @param int $pageId Where the walk starts: the parent of the page asked about
	 * @param array $rules This role's rules by page id
	 * @return bool
	 *
	 */
	protected function inheritedDeny(int $roleId, int $pageId, array $rules) {
		$adminRoot = (int) $this->wire()->config->adminRootPageID;
		$walked = array();
		$deny = false;
		while($pageId > 0 && $pageId !== $adminRoot) {
			if(isset($this->inherited[$roleId][$pageId])) {
				$deny = $this->inherited[$roleId][$pageId];
				break;
			}
			$walked[] = $pageId;
			if(isset($rules[$pageId]) && $rules[$pageId]['inherit']) {
				$deny = $rules[$pageId]['mode'] === BridgeAccessRules::modeDeny;
				break;
			}
			$pageId = $this->parentId($pageId);
		}
		foreach($walked as $id) $this->inherited[$roleId][$id] = $deny;
		return $deny;
	}

	/**
	 * Does any of the user's roles deny the page?
	 *
	 * @param Page $page
	 * @param User $user
	 * @param Page|null $parent Ask as if the page were under this parent (default: where it is)
	 * @return bool
	 *
	 */
	protected function userDenied(Page $page, User $user, ?Page $parent = null) {
		foreach(array_unique(array_column($this->rulesFor($user), 'role')) as $roleId) {
			if($this->roleDenies((int) $roleId, $page, $parent)) return true;
		}
		return false;
	}

	/**
	 * The pages below a denied page that stay allowed to the user: those named by the user's allow
	 * rules that no role of the user denies, and the admin root below the home page
	 *
	 * @param int $root
	 * @param User $user
	 * @return array Page id => is what lies below that page allowed too
	 *
	 */
	protected function exceptionsBelow(int $root, User $user) {
		$config = $this->wire()->config;
		$pages = $this->wire()->pages;
		$out = array();
		if($root === (int) $config->rootPageID) $out[(int) $config->adminRootPageID] = true;
		foreach($this->rulesFor($user) as $rule) {
			if($rule['mode'] !== BridgeAccessRules::modeAllow || !$this->isBelow($rule['page'], $root)) continue;
			$allowed = $pages->get($rule['page']);
			if($allowed->id && !$this->userDenied($allowed, $user)) $out[(int) $allowed->id] = !$this->childrenDenied((int) $allowed->id, $user);
		}
		return $out;
	}

	/**
	 * Does a page lie somewhere below another?
	 *
	 * @param int $pageId
	 * @param int $ancestorId
	 * @return bool
	 *
	 */
	protected function isBelow(int $pageId, int $ancestorId) {
		$id = $this->parentId($pageId);
		while($id > 0 && $id !== $ancestorId) $id = $this->parentId($id);
		return $id === $ancestorId;
	}

	/**
	 * Would a role of the user deny a child of this page that has no rule of its own?
	 *
	 * @param int $pageId
	 * @param User $user
	 * @return bool
	 *
	 */
	protected function childrenDenied(int $pageId, User $user) {
		$index = $this->roleIndex();
		foreach(array_unique(array_column($this->rulesFor($user), 'role')) as $roleId) {
			if($this->inheritedDeny((int) $roleId, $pageId, $index[$roleId])) return true;
		}
		return false;
	}

	/**
	 * The ancestors of the pages the user's allow rules name, when no role of the user denies them
	 *
	 * @param User $user
	 * @return array Page id => true
	 *
	 */
	protected function passThroughIds(User $user) {
		$userId = (int) $user->id;
		if(isset($this->passThrough[$userId])) return $this->passThrough[$userId];
		$pages = $this->wire()->pages;
		$ids = array();
		foreach($this->rulesFor($user) as $rule) {
			if($rule['mode'] !== BridgeAccessRules::modeAllow) continue;
			$allowed = $pages->get($rule['page']);
			if(!$allowed->id || $this->userDenied($allowed, $user)) continue;
			$id = (int) $allowed->parent_id;
			while($id > 0 && !isset($ids[$id])) {
				$ids[$id] = true;
				$id = $this->parentId($id);
			}
		}
		return $this->passThrough[$userId] = $ids;
	}

	/**
	 * A page's parent id; pages are in memory after the first time
	 *
	 * @param int $pageId
	 * @return int
	 *
	 */
	protected function parentId(int $pageId) {
		if(!isset($this->parentIds[$pageId])) {
			$this->parentIds[$pageId] = (int) $this->wire()->pages->get($pageId)->parent_id;
		}
		return $this->parentIds[$pageId];
	}
}

<?php namespace ProcessWire;

/**
 * Prepares the sandbox for admin work: installs AdminThemeBridge (junctioned into app/modules
 * by tools/sandbox-site.sh) and creates two superusers that differ only in admin theme:
 *
 *   bridge  -> AdminThemeBridge
 *   uikit   -> AdminThemeUikit
 *
 * Both share one generated password, written to <sandbox>/.credentials (sandbox/ is gitignored).
 * Idempotent: re-running keeps the password and only fixes what differs.
 *
 * Usage: php tools/sandbox-admin.php /path/to/sandbox/root
 */

$root = rtrim(str_replace('\\', '/', $argv[1] ?? ''), '/');
if(!is_file("$root/index.php") || !is_file("$root/project.php")) {
	exit("Usage: php tools/sandbox-admin.php /path/to/sandbox/root\n");
}

// some sites read $_SERVER['DOCUMENT_ROOT'] in config (StaticPages); CLI has none
if(empty($_SERVER['DOCUMENT_ROOT'])) $_SERVER['DOCUMENT_ROOT'] = $root;
include "$root/index.php";
/** @var ProcessWire $wire */
/** @var Modules $modules */
/** @var Users $users */
/** @var Config $config */

$themes = array('bridge' => 'AdminThemeBridge', 'uikit' => 'AdminThemeUikit');

// some sites keep classes in site/shared/classes/ and autoload them only from the front-end
// prepend file, while save hooks (which fire on the user saves below) reference them; a
// last-resort autoloader for that directory keeps the CLI setup working on such sites
spl_autoload_register(function($class) use($config) {
	$base = basename(str_replace('\\', '/', $class));
	foreach(array('shared/classes/', 'classes/') as $dir) {
		$f = $config->paths->site . $dir . $base . '.php';
		if(is_file($f)) {
			include_once($f);
			return;
		}
	}
});

// the database copy carries WireCache entries computed on the original layout (for example
// AdminThemeBoss caches its CSS URL with expireNever); drop everything except module caches
/** @var WireDatabasePDO $database */
$database = $wire->database;
$dropped = $database->exec("DELETE FROM caches WHERE name NOT LIKE 'Modules.%'");
echo "ok   $dropped cached entries dropped (URLs/paths cached on the original layout)
";

$modules->refresh();
foreach(array_merge(array_unique($themes), array('ProcessBridgeDemo')) as $theme) {
	if($modules->isInstalled($theme)) {
		echo "ok   $theme installed\n";
	} else if($modules->isInstallable($theme)) {
		$modules->install($theme);
		echo "ok   $theme installed now\n";
	} else {
		exit("FAIL $theme not installable (is app/modules/$theme present?)\n");
	}
}

// AdminThemeBoss with "activate for all users" rewrites every user's admin_theme to Uikit on
// each request (AdminThemeBoss::init), which would undo the per-user themes below
if($modules->isInstalled('AdminThemeBoss')) {
	$bossConfig = $modules->getConfig('AdminThemeBoss');
	if(!empty($bossConfig['allusers'])) {
		$bossConfig['allusers'] = 0;
		$modules->saveConfig('AdminThemeBoss', $bossConfig);
		echo "ok   AdminThemeBoss 'allusers' switched off (it forces Uikit for everyone)
";
	}
}

$credFile = "$root/.credentials";
$pass = '';
if(is_file($credFile)) {
	foreach(file($credFile, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) as $line) {
		if(strpos($line, '#') === 0) continue;
		list(, $pass) = array_pad(explode(':', $line, 2), 2, '');
		if($pass) break;
	}
}
if(!$pass) $pass = bin2hex(random_bytes(9));

$lines = array("# sandbox superusers, user:password, one password for all; generated by tools/sandbox-admin.php");
foreach($themes as $name => $theme) {
	$u = $users->get("name=$name");
	$u->of(false);
	if(!$u->id) {
		// saved without hooks: site hooks on page save may expect the front-end environment
		// (classes and functions loaded only by the prepend file) and would abort a CLI save
		$u = $users->newUser();
		$u->of(false);
		$u->name = $name;
		$u->pass = $pass;
		$u->addRole('superuser');
		try {
			$users->save($u, array('noHooks' => true));
		} catch(\Throwable $e) {
			// a site hook on page save threw (site bug or front-end-only dependency); report and stop
			exit("FAIL user $name not created, a site save hook failed: " . $e->getMessage() . " in " . $e->getFile() . ":" . $e->getLine() . "\n");
		}
		echo "ok   user $name created\n";
	} else {
		$u->pass = $pass; // an earlier aborted run may have left the user without a password
		echo "ok   user $name exists\n";
	}
	$u->admin_theme = $theme;
	$users->save($u, array('noHooks' => true));
	$lines[] = "$name:$pass";
}
file_put_contents($credFile, implode("\n", $lines) . "\n");
echo "ok   credentials in $credFile\n";
echo "admin url: " . $config->urls->admin . "\n";

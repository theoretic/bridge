#!/usr/bin/env bash
# Builds (or rebuilds) a conformance sandbox for one local OSP site:
#
#   sandbox/<site>/index.php                 copy of bootstrap/index.php
#   sandbox/<site>/project.php               layout: wire under vendor/, site renamed app/
#   sandbox/<site>/vendor/processwire/wire   junction -> D:/install/processwire/wire
#   sandbox/<site>/vendor/autoload.php       when the site has Composer packages (webroot/vendor): loads
#                                            the site's own autoloader, so site code using them runs
#   sandbox/<site>/app/                      copy of the site's site/ (no files, cache, logs, sessions, backups)
#   sandbox/<site>/app/modules/{AdminThemeBridge,BridgeDemo}  junctions -> modules/
#   DB <dbName>_bridge                       dump of the site's database, plus sandbox superusers (see .credentials)
#
# Site code that hardcodes DOCUMENT_ROOT."/site/..." is rewritten to "/app/..." inside the copy, so
# the site runs under the renamed layout; every such file is listed as a finding.
#
# Usage (Git Bash):  bash tools/sandbox-site.sh <site> <port>
#   <site>  name of D:/work/sites/home/<site>.osp
#   <port>  port the sandbox is served on (added to httpHosts as localhost:<port>)
set -eu

SITE="${1:-}"; PORT="${2:-}"
[ -n "$SITE" ] && [ -n "$PORT" ] || { echo "usage: bash tools/sandbox-site.sh <site> <port>"; exit 1; }

HERE="$(cygpath -m "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)")"
SB="$HERE/sandbox/$SITE"
SRC="/d/work/sites/home/$SITE.osp/application/webroot/site"
WIRE_WIN='D:\install\processwire\wire'
M="/d/work/sites/modules/MariaDB-11.8/bin"
DBH="MariaDB-11.8"; DBU="mysql"; DBP="mysql"
PHP="/d/work/sites/modules/PHP-8.5/php"

[ -d "$SRC" ] || { echo "no site dir: $SRC"; exit 1; }

echo "-> site copy $SITE"
rm -rf "$SB/app"
mkdir -p "$SB/app" "$SB/vendor/processwire"
(cd "$SRC" && tar \
	--exclude=./assets/files --exclude=./assets/cache --exclude=./assets/logs \
	--exclude=./assets/sessions --exclude=./assets/backups --exclude=./assets/tmp \
	-cf - .) | (cd "$SB/app" && tar -xf -)
mkdir -p "$SB/app/assets/files" "$SB/app/assets/cache" "$SB/app/assets/logs" "$SB/app/assets/sessions" "$SB/app/assets/backups"

echo "-> database name"
CONFIGS="$(ls "$SB"/app/config*.php 2>/dev/null)"
DBNAME="$(grep -h -m1 '^\s*\$config->dbName' $CONFIGS 2>/dev/null | sed -n -E "1s/.*dbName *= *['\"]([^'\"]+)['\"].*/\1/p")"
[ -n "$DBNAME" ] || { echo "dbName not found in app/config*.php"; exit 1; }
DBCOPY="${DBNAME}_bridge"
echo "   $DBNAME -> $DBCOPY"

echo "-> site code: literal /site/ paths rewritten for the renamed layout"
if [ -f "$SB/app/ready.php" ]; then
	sed -i 's|DOCUMENT_ROOT\."/site/shared/hooks/\*\.php"|__DIR__."/shared/hooks/*.php"|' "$SB/app/ready.php"
fi
grep -rl 'DOCUMENT_ROOT *\. *"/site/\|DOCUMENT_ROOT *\. *'"'"'/site/\|root *\. *"site/\|root *\. *'"'"'site/\|\[DOCUMENT_ROOT\]/site/\|->root}site/' "$SB/app" --include=*.php 2>/dev/null | grep -v "/assets/cache/" | while read -r f; do
	sed -i 's|DOCUMENT_ROOT *\. *"/site/|DOCUMENT_ROOT . "/app/|g; s|DOCUMENT_ROOT *\. *'"'"'/site/|DOCUMENT_ROOT . '"'"'/app/|g' "$f"
	# $config->paths->root . "site/..." and $config->urls->root . 'site/...'
	sed -i 's|root *\. *"site/|root . "app/|g; s|root *\. *'"'"'site/|root . '"'"'app/|g' "$f"
	# "$_SERVER[DOCUMENT_ROOT]/site/..." and "{$config->paths->root}site/..." interpolations
	sed -i 's|\[DOCUMENT_ROOT\]/site/|[DOCUMENT_ROOT]/app/|g; s|->root}site/|->root}app/|g' "$f"
	echo "   patched ${f#$SB/app/}"
done

# PHP files beside index.php in the web root (atispro: geogate.php, sla.events: _app_root.php) are
# sometimes required from site/config.php as __DIR__ . '/../x.php'; copy them next to the sandbox index.php
for f in "$SRC"/../*.php; do
	[ -f "$f" ] || continue
	case "$(basename "$f")" in index.php|install.php) continue;; esac
	cp "$f" "$SB/$(basename "$f")"
	echo "   copied webroot/$(basename "$f")"
done

# compiled copies of site files (FileCompiler) would carry the old paths; always start clean
rm -rf "$SB/app/assets/cache/FileCompiler"

echo "-> wire junction"
if [ ! -e "$SB/vendor/processwire/wire" ]; then
	cmd //c mklink //J "$(cygpath -w "$SB/vendor/processwire/wire")" "$WIRE_WIN" > /dev/null
fi

SITE_AUTOLOAD="/d/work/sites/home/$SITE.osp/application/webroot/vendor/autoload.php"
if [ -f "$SITE_AUTOLOAD" ]; then
	echo "-> vendor/autoload.php -> the site's Composer autoloader"
	printf '%s
' '<?php' "// generated by tools/sandbox-site.sh: the site's Composer packages (read in place)" 		"require_once '$(cygpath -m "$SITE_AUTOLOAD")';" > "$SB/vendor/autoload.php"
fi

echo "-> module junctions app/modules/{AdminThemeBridge,BridgeDemo}"
for m in AdminThemeBridge BridgeDemo; do
	if [ -e "$SB/app/modules/$m" ] && [ ! -L "$SB/app/modules/$m" ]; then
		echo "   app/modules/$m exists as a plain copy in the site; replacing with a junction"
		rm -rf "$SB/app/modules/$m"
	fi
	if [ ! -e "$SB/app/modules/$m" ]; then
		cmd //c mklink //J "$(cygpath -w "$SB/app/modules/$m")" "$(cygpath -w "$HERE/modules/$m")" > /dev/null
	fi
done

echo "-> bootstrap files"
cp "$HERE/bootstrap/index.php" "$SB/index.php"
cat > "$SB/project.php" <<EOF
<?php
// generated by tools/sandbox-site.sh $SITE $PORT
return array(
	'bridge' => '$HERE/bootstrap',
	'wire' => __DIR__ . '/vendor/processwire/wire',
	'site' => __DIR__ . '/app',
);
EOF

echo "-> database copy $DBNAME -> $DBCOPY"
"$M/mariadb" -h "$DBH" -u "$DBU" -p"$DBP" -e "DROP DATABASE IF EXISTS \`$DBCOPY\`; CREATE DATABASE \`$DBCOPY\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
"$M/mariadb-dump" -h "$DBH" -u "$DBU" -p"$DBP" --single-transaction "$DBNAME" | "$M/mariadb" -h "$DBH" -u "$DBU" -p"$DBP" "$DBCOPY"
for f in $CONFIGS; do
	sed -i -E "s/(config->dbName *= *['\"])$DBNAME(['\"])/\1$DBCOPY\2/" "$f"
done
grep -q "$DBCOPY" $CONFIGS 2>/dev/null || { echo "config not pointed at $DBCOPY"; exit 1; }

echo "-> httpHosts: localhost:$PORT"
# appended at the end of config.php so it wins over whatever form the site uses (array(), [], included files)
printf '\n// sandbox: tools/sandbox-site.sh\n$config->httpHosts[] = %s;\n' "'localhost:$PORT'" >> "$SB/app/config.php"
grep -q "localhost:$PORT" "$SB/app/config.php" || { echo "httpHosts not updated"; exit 1; }

echo "-> admin: theme install + sandbox users"
"$PHP" "$HERE/tools/sandbox-admin.php" "$SB"

echo "done: $SB (serve: $PHP -S localhost:$PORT -t sandbox/$SITE tools/router.php)"
